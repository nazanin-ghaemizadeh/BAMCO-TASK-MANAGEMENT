create or replace function private.route_change_request(p_request_id bigint)
returns void language plpgsql security definer set search_path='' as $$
declare
  r public.change_requests%rowtype; policy public.approval_policies%rowtype; wf bigint;
  requester_position bigint; version_no bigint; depth_no integer; parent_id bigint;
  pos record; approver uuid; allowed boolean; snapshot jsonb:='[]'::jsonb; route_step_no integer:=0;
begin
  select * into r from public.change_requests where id=p_request_id for update;
  if not found then raise exception 'درخواست پیدا نشد'; end if;
  select * into policy from public.approval_policies where policy_key in (r.request_type,'task') and active
    order by (policy_key=r.request_type) desc,id limit 1;
  select a.position_id into requester_position from public.organization_position_assignments a
    where a.user_id=r.requested_by and a.is_primary and a.valid_from<=current_date and (a.valid_to is null or a.valid_to>=current_date)
    order by a.id desc limit 1;
  select structure_version into version_no from public.organization_settings where singleton;
  insert into public.organization_workflows(request_id,policy_id,requester_position_id,structure_version,status,current_step,structure_snapshot)
    values(r.id,policy.id,requester_position,coalesce(version_no,1),'in_review',1,'{}'::jsonb) returning id into wf;
  if requester_position is not null then
    for pos in
      with recursive ancestors as(
        select p.id,p.parent_position_id,p.title,ro.role_key,0 as depth_no
        from public.organization_positions p join public.organization_roles ro on ro.id=p.role_id
        where p.id=requester_position
        union all
        select parent.id,parent.parent_position_id,parent.title,ro.role_key,child.depth_no+1
        from public.organization_positions parent
        join ancestors child on child.parent_position_id=parent.id
        join public.organization_roles ro on ro.id=parent.role_id
      )
      select * from ancestors where depth_no>0 order by depth_no
    loop
      exit when route_step_no >= coalesce(policy.max_levels,3);
      select coalesce(a.acting_user_id,pa.user_id) into approver
      from public.organization_positions p
      left join public.organization_position_assignments pa on pa.position_id=p.id and pa.is_primary and pa.valid_to is null
      left join lateral(select acting_user_id from public.organization_position_acting ac where ac.position_id=p.id and ac.valid_from<=current_date and ac.valid_to>=current_date order by ac.id desc limit 1) a on true
      where p.id=pos.id and p.active and (a.acting_user_id is not null or pa.user_id is not null) limit 1;
      allowed := approver is not null and exists(select 1 from public.profiles pr where pr.id=approver and pr.active and pr.id<>r.requested_by)
        and (coalesce(array_length(policy.required_role_keys,1),0)=0 or pos.role_key=any(policy.required_role_keys))
        and (not exists(select 1 from public.approval_policy_steps ps where ps.policy_id=policy.id)
          or exists(select 1 from public.approval_policy_steps ps where ps.policy_id=policy.id and ps.step_no=route_step_no+1 and (ps.role_key is null or ps.role_key=pos.role_key)));
      if allowed then
        route_step_no:=route_step_no+1;
        insert into public.organization_workflow_steps(workflow_id,step_no,position_id,approver_id,role_key,position_title)
          values(wf,route_step_no,pos.id,approver,pos.role_key,pos.title);
        snapshot:=snapshot||jsonb_build_array(jsonb_build_object('step_no',route_step_no,'position_id',pos.id,'position_title',pos.title,'role_key',pos.role_key,'approver_id',approver));
      end if;
    end loop;
  end if;
  if route_step_no=0 then
    update public.organization_workflows set status='blocked',blocked_reason=case when requester_position is null then 'برای ثبت‌کننده سمت سازمانی فعال تعیین نشده است.' else 'بالادست فعال و قابل تأیید پیدا نشد.' end,structure_snapshot=snapshot,updated_at=now() where id=wf;
    update public.change_requests set organization_workflow_id=wf,requester_position_id=requester_position,request_status='pending',current_stage=1 where id=r.id;
  else
    update public.organization_workflows set structure_snapshot=snapshot,updated_at=now() where id=wf;
    update public.change_requests set organization_workflow_id=wf,requester_position_id=requester_position,request_status='in_review',current_stage=1,approval_chain_id=null where id=r.id;
    select approver_id into approver from public.organization_workflow_steps where workflow_id=wf and step_no=1;
    if approver is not null then
      begin perform private.create_portal_event(approver,'درخواست جدید برای تأیید','یک درخواست در کارتابل شما قرار گرفت.','approval_request','change_request',r.id::text); exception when others then null; end;
    end if;
  end if;
  insert into public.change_request_events(request_id,actor_id,event_type,note,snapshot)
    values(r.id,auth.uid(),'routed',case when route_step_no=0 then 'گردش سازمانی متوقف شد؛ ساختار سازمانی نیازمند تکمیل است.' else 'درخواست بر اساس ساختار سازمانی وارد گردش شد.' end,jsonb_build_object('workflow_id',wf,'structure_version',version_no,'steps',snapshot));
end $$;

create or replace function public.submit_change_request(p_request_type text,p_task_id bigint,p_proposed_data jsonb,p_note text default null)
returns bigint language plpgsql security definer set search_path='' as $$
declare rid bigint; owned boolean; before_snapshot jsonb;
begin
  if p_request_type not in ('create','update','status','priority','description','complete','delete','due_date') then raise exception 'نوع درخواست نامعتبر است'; end if;
  if p_request_type='create' then
    p_proposed_data=coalesce(p_proposed_data,'{}'::jsonb)||jsonb_build_object('owner_id',null,'status','ثبت شده','start_date',null,'due_date',null,'done_date',null);
  else
    select exists(select 1 from public.tasks where id=p_task_id and owner_id=auth.uid()) into owned;
    if not owned and not private.is_manager() and not public.organization_has_permission('project.edit',null) then raise exception 'این وظیفه در محدوده دسترسی شما نیست'; end if;
    select to_jsonb(t) into before_snapshot from public.tasks t where t.id=p_task_id;
  end if;
  insert into public.change_requests(task_id,request_type,before_data,proposed_data,requested_by,request_status,requester_note)
    values(p_task_id,p_request_type,before_snapshot,coalesce(p_proposed_data,'{}'::jsonb),auth.uid(),'pending',p_note) returning id into rid;
  perform private.route_change_request(rid);
  return rid;
end $$;

create or replace function public.review_request_stage(p_request_id bigint,p_decision text,p_note text default null,p_final_data jsonb default null)
returns text language plpgsql security definer set search_path='' as $$
declare r public.change_requests%rowtype; wf public.organization_workflows%rowtype; step public.organization_workflow_steps%rowtype; next_step integer; payload jsonb;
begin
  if p_decision not in ('approved','rejected','needs_revision') then raise exception 'تصمیم نامعتبر است'; end if;
  select * into r from public.change_requests where id=p_request_id and request_status in ('pending','in_review','needs_revision') for update;
  if not found then raise exception 'درخواست باز پیدا نشد'; end if;
  if r.organization_workflow_id is null then raise exception 'این درخواست در گردش سازمانی نیست؛ رکورد تاریخی فقط قابل مشاهده است.'; end if;
  select * into wf from public.organization_workflows where id=r.organization_workflow_id for update;
  select * into step from public.organization_workflow_steps where workflow_id=wf.id and step_no=wf.current_step and approver_id=auth.uid() and decision='pending' for update;
  if not found then raise exception 'این درخواست در کارتابل شما نیست'; end if;
  update public.organization_workflow_steps set decision=p_decision,note=p_note,decided_at=now() where id=step.id;
  insert into public.change_request_events(request_id,actor_id,event_type,note,snapshot) values(r.id,auth.uid(),p_decision,p_note,jsonb_build_object('workflow_id',wf.id,'step_no',wf.current_step));
  if p_decision='rejected' then update public.organization_workflows set status='rejected',updated_at=now() where id=wf.id; update public.change_requests set request_status='rejected',manager_note=p_note,reviewed_by=auth.uid(),reviewed_at=now(),completed_at=now() where id=r.id; return 'rejected'; end if;
  if p_decision='needs_revision' then update public.organization_workflows set status='needs_revision',updated_at=now() where id=wf.id; update public.change_requests set request_status='needs_revision',manager_note=p_note,reviewed_by=auth.uid(),reviewed_at=now() where id=r.id; begin perform private.create_portal_event(r.requested_by,'درخواست برای اصلاح برگشت داده شد',coalesce(p_note,'لطفاً درخواست را اصلاح کنید.'),'request_revision','change_request',r.id::text); exception when others then null; end; return 'needs_revision'; end if;
  select min(step_no) into next_step from public.organization_workflow_steps where workflow_id=wf.id and step_no>wf.current_step;
  if next_step is not null then update public.organization_workflows set current_step=next_step,updated_at=now() where id=wf.id; update public.change_requests set current_stage=next_step where id=r.id; select approver_id into step.approver_id from public.organization_workflow_steps where workflow_id=wf.id and step_no=next_step; begin perform private.create_portal_event(step.approver_id,'درخواست جدید برای تأیید','درخواست به مرحله بعدی گردش رسید.','approval_request','change_request',r.id::text); exception when others then null; end; return 'next_stage'; end if;
  payload:=coalesce(p_final_data,r.proposed_data); perform private.apply_change_request(r.id,auth.uid(),payload);
  update public.organization_workflows set status='approved',updated_at=now() where id=wf.id;
  return 'approved';
end $$;

create or replace function public.resubmit_change_request(p_request_id bigint,p_proposed_data jsonb)
returns void language plpgsql security definer set search_path='' as $$
begin
  update public.change_requests set proposed_data=coalesce(p_proposed_data,'{}'::jsonb),request_status='pending',revision_count=revision_count+1,resubmitted_at=now(),reviewed_by=null,reviewed_at=null,manager_note=null,current_stage=1,completed_at=null,final_data=null,applied_task_id=null,organization_workflow_id=null where id=p_request_id and requested_by=auth.uid() and request_status='needs_revision';
  if not found then raise exception 'درخواست قابل اصلاح پیدا نشد'; end if;
