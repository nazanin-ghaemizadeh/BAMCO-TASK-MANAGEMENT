create or replace function public.request_routing_status()
returns table(request_id bigint,stage_no smallint,stage_title text,approver_names text,actionable boolean)
language sql stable security definer set search_path='' as $$
  select r.id,w.current_step::smallint,coalesce(string_agg(distinct s.position_title,'، ' order by s.position_title),'بدون بالادست'),
    string_agg(distinct p.full_name,'، ' order by p.full_name),
    coalesce(bool_or(s.approver_id=auth.uid() and s.decision='pending'),false)
  from public.change_requests r join public.organization_workflows w on w.id=r.organization_workflow_id
  join public.organization_workflow_steps s on s.workflow_id=w.id and s.step_no=w.current_step
  left join public.profiles p on p.id=s.approver_id
  where r.request_status in ('pending','in_review','needs_revision')
    and (r.requested_by=auth.uid() or s.approver_id=auth.uid() or public.organization_has_permission('request.approve',r.requested_by))
  group by r.id,w.current_step;
$$;

create or replace function public.request_workflow_snapshot()
returns jsonb language plpgsql stable security definer set search_path='' as $$
declare current_rows jsonb; history_rows jsonb; routes jsonb; me uuid:=auth.uid();
begin
  select coalesce(jsonb_agg(to_jsonb(r) order by r.created_at desc,r.id desc),'[]'::jsonb) into current_rows
  from public.change_requests r left join public.organization_workflows w on w.id=r.organization_workflow_id
  where r.request_status in ('pending','in_review','needs_revision') and (r.requested_by=me or exists(select 1 from public.organization_workflow_steps s where s.workflow_id=w.id and s.approver_id=me and s.step_no=w.current_step and s.decision='pending') or public.organization_has_permission('request.approve',r.requested_by));
  select coalesce(jsonb_agg(to_jsonb(r) order by coalesce(r.reviewed_at,r.completed_at,r.created_at) desc,r.id desc),'[]'::jsonb) into history_rows
  from public.change_requests r where r.request_status in ('approved','rejected','cancelled') and (r.requested_by=me or public.organization_has_permission('request.approve',r.requested_by));
  select coalesce(jsonb_agg(to_jsonb(x)),'[]'::jsonb) into routes from public.request_routing_status() x;
  return jsonb_build_object('current_requests',current_rows,'history_requests',history_rows,'routes',routes);
end $$;

