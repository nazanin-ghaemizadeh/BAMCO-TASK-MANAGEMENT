-- Migrate open requests once. Terminal requests keep their old chain and step
-- history untouched; an open request gets a new hierarchy snapshot or a
-- visible blocked state that an administrator can resolve by completing the tree.
do $$
declare r record;
begin
  for r in select id from public.change_requests
    where request_status in ('pending','in_review','needs_revision')
      and organization_workflow_id is null order by id
  loop
    begin
      perform private.route_change_request(r.id);
    exception when others then
      insert into public.audit_trail(actor_id,action,target_type,target_id,metadata)
        values(auth.uid(),'migration_blocked','change_request',r.id::text,jsonb_build_object('reason',sqlerrm));
    end;
  end loop;
end $$;

