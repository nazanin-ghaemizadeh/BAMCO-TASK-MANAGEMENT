create or replace function private.platform_can_manage_org(p_user uuid default auth.uid())
returns boolean language sql stable security definer set search_path='' as $$
  select exists(select 1 from public.profiles p where p.id=p_user and p.active and p.role='manager')
    or exists(
      select 1 from public.organization_position_assignments a
      join public.organization_positions pos on pos.id=a.position_id and pos.active
      join public.organization_roles r on r.id=pos.role_id and r.active
      join public.organization_role_permissions rp on rp.role_id=r.id and rp.permission_key='organization.manage' and rp.allowed
      where a.user_id=p_user and a.is_primary and a.valid_to is null
    );
$$;

create or replace function public.organization_scope_user_ids(p_actor uuid default auth.uid())
returns table(user_id uuid)
language sql stable security definer set search_path='' as $$
  with recursive roots as(
    select a.position_id from public.organization_position_assignments a
    where a.user_id=p_actor and a.is_primary and a.valid_from<=current_date
      and (a.valid_to is null or a.valid_to>=current_date)
  ), tree as(
    select p.id from public.organization_positions p join roots r on r.position_id=p.id
    union all
    select child.id from public.organization_positions child join tree parent on child.parent_position_id=parent.id
    where child.active
  )
  select distinct a.user_id from public.organization_position_assignments a
  join tree t on t.id=a.position_id
  where a.valid_from<=current_date and (a.valid_to is null or a.valid_to>=current_date)
  union select p_actor where p_actor is not null;
$$;

create or replace function public.organization_has_permission(p_permission text,p_target_user uuid default null)
returns boolean language sql stable security definer set search_path='' as $$
  select exists(
    select 1
    from public.organization_position_assignments a
    join public.organization_positions pos on pos.id=a.position_id and pos.active
    join public.organization_roles r on r.id=pos.role_id and r.active
    join public.organization_role_permissions rp on rp.role_id=r.id and rp.permission_key=p_permission and rp.allowed
    where a.user_id=auth.uid() and a.is_primary and a.valid_from<=current_date
      and (a.valid_to is null or a.valid_to>=current_date)
      and (p_target_user is null or p_target_user in (select user_id from public.organization_scope_user_ids(auth.uid())))
  ) or exists(select 1 from public.profiles p where p.id=auth.uid() and p.active and p.role='manager');
$$;

create or replace function private.platform_audit_trigger()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  insert into public.audit_trail(actor_id,action,target_type,target_id,old_data,new_data,metadata)
  values(auth.uid(),lower(tg_op),tg_table_name,coalesce(to_jsonb(old)->>'id',to_jsonb(new)->>'id',''),
    case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) end,
    case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) end,'{}'::jsonb);
  if tg_op='DELETE' then return old; end if;
  return new;
end $$;

create or replace function private.bump_organization_version()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  update public.organization_settings set structure_version=structure_version+1,updated_at=now(),updated_by=auth.uid() where singleton;
  return case when tg_op='DELETE' then old else new end;
end $$;
