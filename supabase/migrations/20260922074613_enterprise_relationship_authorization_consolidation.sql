create or replace function private._bamco_impl_chat_system_message_payload(p_message_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $$
declare
  v_chat_message public.chat_messages%rowtype;
  v_portal_message public.portal_messages%rowtype;
  v_delivery public.message_deliveries%rowtype;
  v_snapshot public.message_snapshots%rowtype;
  v_sender text;
begin
  select * into v_chat_message
  from public.chat_messages message
  where message.id=p_message_id
    and message.source_portal_message_id is not null
    and message.deleted_at is null;
  if not found or not private.can_access_chat(v_chat_message.thread_id) then
    raise exception 'دسترسی ندارید' using errcode='42501';
  end if;
