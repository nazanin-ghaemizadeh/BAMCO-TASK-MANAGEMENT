create or replace function public.organization_scope_user_ids(p_actor uuid default auth.uid())
returns table(user_id uuid)
language plpgsql
stable
security definer
set search_path=''
as $$
begin
  if auth.uid() is null then return; end if;
  if not (
    public.can_access_feature('organization','view')
    or public.can_access_feature('kanban','view')
    or public.can_access_feature('archive','view')
  ) then
    raise exception 'مجوز مشاهدهٔ دامنه سازمانی ندارید.' using errcode='42501';
  end if;
  if p_actor is distinct from auth.uid() and not private.is_system_manager(auth.uid()) then
    raise exception 'دامنه سازمانی فقط برای کاربر جاری قابل محاسبه است.' using errcode='42501';
  end if;
  if private.is_system_manager(p_actor) then
    return query select profile.id from public.profiles profile where profile.active;
    return;
  end if;
  return query
    with roots as (
      select position_id from private.organization_active_primary_positions(p_actor)
    ), tree as (
      select branch.position_id
      from roots root
      cross join lateral private.organization_descendant_position_ids(root.position_id) branch
    )
    select distinct assignment.user_id
    from public.organization_position_assignments assignment
    join tree on tree.position_id=assignment.position_id
    join public.profiles profile on profile.id=assignment.user_id and profile.active
    where assignment.is_primary
      and assignment.valid_from<=current_date
      and (assignment.valid_to is null or assignment.valid_to>current_date)
    union
    select p_actor;
end;
$$;

create or replace function public.organization_scope()
returns jsonb
language sql
stable
security definer
set search_path=''
as $$
  with recursive own_positions as (
    select position_id from private.organization_active_primary_positions(auth.uid())
  ), parents as (
    select position.parent_position_id as position_id
    from public.organization_positions position
    join own_positions own on own.position_id=position.id
    where position.parent_position_id is not null
  ), recursive_ancestors(position_id) as (
    select position_id from parents
    union
    select position.parent_position_id
    from public.organization_positions position
    join recursive_ancestors ancestor on ancestor.position_id=position.id
    where position.parent_position_id is not null
  ), direct_reports as (
    select distinct assignment.user_id
    from public.organization_positions position
    join own_positions own on own.position_id=position.parent_position_id
    join public.organization_position_assignments assignment on assignment.position_id=position.id
    join public.profiles profile on profile.id=assignment.user_id and profile.active
    where position.active and assignment.is_primary
      and assignment.valid_from<=current_date
      and (assignment.valid_to is null or assignment.valid_to>current_date)
  )
  select jsonb_build_object(
    'own_position_ids',coalesce((select jsonb_agg(position_id) from own_positions),'[]'::jsonb),
    'direct_parent_position_ids',coalesce((select jsonb_agg(position_id) from parents),'[]'::jsonb),
    'ancestor_position_ids',coalesce((select jsonb_agg(position_id) from recursive_ancestors),'[]'::jsonb),
    'direct_report_user_ids',coalesce((select jsonb_agg(user_id) from direct_reports),'[]'::jsonb),
    'descendant_user_ids',coalesce((select jsonb_agg(user_id) from private.organization_strict_descendant_user_ids(auth.uid())),'[]'::jsonb),
    'user_ids',coalesce((select jsonb_agg(user_id) from public.organization_scope_user_ids(auth.uid())),'[]'::jsonb)
  );
$$;

