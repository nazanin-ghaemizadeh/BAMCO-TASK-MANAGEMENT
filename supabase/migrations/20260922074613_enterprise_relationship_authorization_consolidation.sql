create or replace function private.enforce_task_hierarchy_scope()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_actor uuid:=auth.uid();
begin
  if current_setting('bamco.approval_apply',true)='1'
     or current_setting('bamco.resequencing',true)='1'
     or nullif(current_setting('bamco.deleting_person',true),'') is not null
     or auth.role()='service_role'
     or v_actor is null then
    return new;
  end if;
  if tg_op='INSERT' then
    if new.created_by is distinct from v_actor then
      raise exception 'ثبت‌کنندهٔ وظیفه باید کاربر جاری باشد.' using errcode='42501';
    end if;
    if not public.organization_can_assign_task(new.owner_id) then
      raise exception 'ثبت مستقیم فقط برای زیردست سازمانی یا مجوز عبور از تأیید مجاز است.' using errcode='42501';
    end if;
  else
    if new.created_by is distinct from old.created_by then
      raise exception 'ثبت‌کنندهٔ وظیفه قابل تغییر نیست.' using errcode='42501';
    end if;
    if not public.organization_can_manage_task(old.id) then
      raise exception 'ویرایش مستقیم فقط برای وظیفهٔ زیردست سازمانی مجاز است.' using errcode='42501';
    end if;
    if not private.organization_actor_can_direct_manage_user(v_actor,coalesce(new.owner_id,new.created_by)) then
      raise exception 'متولی جدید در محدودهٔ مدیریت مستقیم شما نیست.' using errcode='42501';
    end if;
  end if;
  return new;
end;
$$;
