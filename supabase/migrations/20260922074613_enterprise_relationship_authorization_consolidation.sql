create or replace function private._bamco_impl_chat_clear_system_thread(p_thread_id uuid)
returns integer
language plpgsql
security definer
set search_path=''
as $$
declare
  v_actor uuid:=auth.uid();
  v_count integer:=0;
begin
  if v_actor is null
     or not private.feature_can_access_for(v_actor,'messages','edit')
     or not private.can_access_chat(p_thread_id)
     or not exists(
       select 1 from public.chat_threads thread
       where thread.id=p_thread_id and thread.system_recipient_id=v_actor
     ) then
    raise exception 'فقط زنجیره خودکار مربوط به حساب خودتان قابل پاک کردن است' using errcode='42501';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('system-chat:'||v_actor::text,0));
  select count(*) into v_count from public.chat_messages where thread_id=p_thread_id;
  insert into private.system_chat_resets(user_id,cleared_at)
  values(v_actor,clock_timestamp())
  on conflict(user_id) do update set cleared_at=excluded.cleared_at;
  update public.portal_message_recipients recipient
  set dismissed_at=clock_timestamp(),read_at=coalesce(recipient.read_at,clock_timestamp())
  where recipient.recipient_id=v_actor
    and recipient.message_id in (
      select message.source_portal_message_id
      from public.chat_messages message
      where message.thread_id=p_thread_id and message.source_portal_message_id is not null
    );
  delete from public.notifications
  where user_id=v_actor and entity_type='chat_thread' and entity_id=p_thread_id::text;
  delete from public.chat_threads where id=p_thread_id and system_recipient_id=v_actor;
