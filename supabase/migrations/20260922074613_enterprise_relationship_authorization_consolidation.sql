create or replace function private.organization_strict_descendant_user_ids(p_actor uuid)
returns table(user_id uuid)
language sql
stable
security definer
set search_path=''
as $$
  with roots as (
    select position_id from private.organization_active_primary_positions(p_actor)
  ), descendants as (
    select child.position_id
    from roots root
    cross join lateral private.organization_descendant_position_ids(root.position_id) child
    where child.position_id<>root.position_id
  )
  select distinct assignment.user_id
  from public.organization_position_assignments assignment
  join descendants descendant on descendant.position_id=assignment.position_id
  join public.profiles profile on profile.id=assignment.user_id and profile.active
  where assignment.is_primary
    and assignment.valid_from<=current_date
    and (assignment.valid_to is null or assignment.valid_to>current_date);
