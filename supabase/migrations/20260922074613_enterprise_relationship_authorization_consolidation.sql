create or replace function public.request_routing_status()
returns table(request_id bigint,stage_no smallint,stage_title text,approver_names text,actionable boolean)
language sql
stable
security definer
set search_path=''
as $$
  select request.id,workflow.current_step::smallint,
    coalesce(string_agg(distinct step.position_title,'، ' order by step.position_title),'بدون بالادست'),
    string_agg(distinct coalesce(nullif(profile.display_name,''),nullif(profile.full_name,''),profile.email::text),'، ' order by coalesce(nullif(profile.display_name,''),nullif(profile.full_name,''),profile.email::text)),
    coalesce(bool_or(step.approver_id=auth.uid() and step.decision='pending'),false)
  from public.change_requests request
  join public.organization_workflows workflow on workflow.id=request.organization_workflow_id
  join public.organization_workflow_steps step on step.workflow_id=workflow.id and step.step_no=workflow.current_step
  left join public.profiles profile on profile.id=step.approver_id
  where request.request_status in ('pending','in_review','needs_revision')
    and (
      request.requested_by=auth.uid()
      or step.approver_id=auth.uid()
      or private.is_system_manager(auth.uid())
    )
  group by request.id,workflow.current_step;
$$;

create or replace function public.request_workflow_snapshot()
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $$
declare
  v_current jsonb;
  v_history jsonb;
  v_routes jsonb;
  v_actor uuid:=auth.uid();
begin
  if v_actor is null or not private.feature_can_access_for(v_actor,'approvals','view') then
    raise exception 'دسترسی کارتابل تأیید ندارید.' using errcode='42501';
  end if;
  select coalesce(jsonb_agg(to_jsonb(request) order by request.created_at desc,request.id desc),'[]'::jsonb)
    into v_current
  from public.change_requests request
  left join public.organization_workflows workflow on workflow.id=request.organization_workflow_id
  where request.request_status in ('pending','in_review','needs_revision')
    and (
      request.requested_by=v_actor
      or exists(
        select 1 from public.organization_workflow_steps step
        where step.workflow_id=workflow.id and step.step_no=workflow.current_step
          and step.approver_id=v_actor and step.decision='pending'
      )
      or private.is_system_manager(v_actor)
    );
  select coalesce(jsonb_agg(to_jsonb(request) order by coalesce(request.reviewed_at,request.completed_at,request.created_at) desc,request.id desc),'[]'::jsonb)
    into v_history
  from public.change_requests request
  where request.request_status in ('approved','rejected','cancelled')
    and private.request_user_is_participant(request.id,v_actor);
  select coalesce(jsonb_agg(to_jsonb(route)),'[]'::jsonb) into v_routes
  from public.request_routing_status() route;
  return jsonb_build_object(
    'schema','bamco.workflow.v2',
    'current_requests',v_current,
    'history_requests',v_history,
    'routes',v_routes
  );
end;
$$;

