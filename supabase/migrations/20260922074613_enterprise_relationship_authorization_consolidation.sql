create or replace function private.guard_profile_update()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_self_email_write boolean:=auth.uid()=old.id and current_setting('bamco.profile_self_update',true)='1';
begin
  if not private.is_system_manager(auth.uid()) and (
    old.role is distinct from new.role
    or old.active is distinct from new.active
    or (old.email is distinct from new.email and not v_self_email_write)
    or old.full_name is distinct from new.full_name
    or (old.must_change_password is distinct from new.must_change_password and new.must_change_password)
  ) then
    raise exception 'تغییر این فیلدها مجاز نیست' using errcode='42501';
  end if;
  new.updated_at=now();
  return new;
end;
$$;

create or replace function private.protect_profile_sensitive_fields()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_self_email_write boolean:=auth.uid()=old.id and current_setting('bamco.profile_self_update',true)='1';
begin
  if auth.uid() is null then return new; end if;
  if not private.is_system_manager(auth.uid()) then
    if new.id is distinct from old.id
       or (new.email is distinct from old.email and not v_self_email_write)
       or new.full_name is distinct from old.full_name
