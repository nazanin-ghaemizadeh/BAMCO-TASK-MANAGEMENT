-- The workbench list is filtered by the same RLS predicate.  No client-side
-- route filter can reveal a thread whose feature grant was revoked.
create or replace function private._bamco_impl_chat_conversation_list()
returns jsonb
language sql
stable
security definer
set search_path=''
as $$
  select coalesce(jsonb_agg(row_data order by (row_data.system_recipient_id is not null) desc,row_data.updated_at desc),'[]'::jsonb)
  from (
    select
      thread.id,
      thread.thread_type,
      thread.task_id,
      thread.avatar_path,
      thread.system_recipient_id,
      thread.is_active,
      thread.participant_deleted_at,
      case
        when thread.system_recipient_id is not null then 'پیام‌های خودکار سامانه'
        when thread.thread_type='direct' then coalesce(
          nullif(peer.display_name,''),nullif(peer.full_name,''),peer.email::text,
          thread.deleted_participant_name,thread.title
        )
        else thread.title
      end as title,
      peer.id as person_id,
      thread.updated_at,
      (
        select case
          when message.body like 'BAMCO_PORTAL_MESSAGE_V1:%'
            then coalesce((select portal.subject from public.portal_messages portal where portal.id=message.source_portal_message_id),'پیام سامانه')
          else left(message.body,160)
        end
        from public.chat_messages message
        where message.thread_id=thread.id and message.deleted_at is null
        order by message.created_at desc
        limit 1
      ) as last_message,
      (
        select count(*)
        from public.notifications notification
        where notification.user_id=auth.uid()
          and notification.entity_type='chat_thread'
          and notification.entity_id=thread.id::text
          and notification.read_at is null
          and notification.dismissed_at is null
      ) as unread_count
    from public.chat_threads thread
    left join lateral (
      select profile.id,profile.display_name,profile.full_name,profile.email
      from public.chat_members member
      join public.profiles profile on profile.id=member.user_id
      where member.thread_id=thread.id
        and member.user_id<>auth.uid()
        and profile.id is distinct from thread.system_recipient_id
      order by member.joined_at
      limit 1
    ) peer on true
    where auth.uid() is not null
      and (thread.is_active or thread.participant_deleted_at is not null or thread.system_recipient_id=auth.uid())
      and private.can_access_chat(thread.id)
  ) row_data;
$$;

-- RPC mutations all verify both the action grant and the contextual relation.
-- The public wrappers remain stable; they call these SECURITY DEFINER
-- implementations while each implementation derives the actor from auth.uid.
create or replace function private._bamco_impl_chat_create_group(
  p_title text,
  p_member_ids uuid[] default '{}'::uuid[]
)
returns uuid
language plpgsql
security definer
set search_path=''
as $$
declare
  v_actor uuid:=auth.uid();
  v_thread_id uuid;
  v_member uuid;
begin
  if v_actor is null or not private.feature_can_access_for(v_actor,'groupChat','create') then
    raise exception 'forbidden' using errcode='42501';
  end if;
  if length(btrim(coalesce(p_title,'')))<2 then
    raise exception 'title_required' using errcode='22023';
  end if;

  insert into public.chat_threads(thread_type,title,created_by)
  values('group',left(btrim(p_title),120),v_actor)
  returning id into v_thread_id;
  insert into public.chat_members(thread_id,user_id,member_role)
  values(v_thread_id,v_actor,'owner')
  on conflict do nothing;

  foreach v_member in array coalesce(p_member_ids,'{}'::uuid[])
  loop
    if v_member is distinct from v_actor
       and exists(
         select 1 from public.profiles profile
