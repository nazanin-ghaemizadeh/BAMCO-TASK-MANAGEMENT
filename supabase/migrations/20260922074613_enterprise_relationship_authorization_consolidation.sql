  set title=left(btrim(p_title),120),updated_at=now()
  where id=p_thread_id;
  delete from public.chat_members
  where thread_id=p_thread_id and member_role<>'owner';
  foreach v_member in array coalesce(p_member_ids,'{}'::uuid[])
  loop
    if exists(
      select 1 from public.profiles profile
      where profile.id=v_member and profile.active and profile.messaging_enabled
    ) and private.feature_can_access_for(v_member,'groupChat','view') then
      insert into public.chat_members(thread_id,user_id)
