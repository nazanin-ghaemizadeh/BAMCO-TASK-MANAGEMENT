-- Chat clients receive RLS-filtered Postgres changes just like the other
-- canonical domains.  The publication add is safe on both fresh and existing
-- projects, and a revoked grant prevents the client from reading the row.
do $$
declare
  v_table text;
begin
  foreach v_table in array array['chat_threads','chat_members','chat_messages']
  loop
    if not exists(
      select 1
      from pg_publication_rel publication_rel
      join pg_publication publication on publication.oid=publication_rel.prpubid
      join pg_class relation on relation.oid=publication_rel.prrelid
      join pg_namespace namespace on namespace.oid=relation.relnamespace
      where publication.pubname='supabase_realtime'
        and namespace.nspname='public'
        and relation.relname=v_table
    ) then
      execute format('alter publication supabase_realtime add table public.%I',v_table);
    end if;
  end loop;
end;
$$;

