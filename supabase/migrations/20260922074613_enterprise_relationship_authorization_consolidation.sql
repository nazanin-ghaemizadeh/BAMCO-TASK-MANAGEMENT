  select * into v_delivery from public.message_deliveries where portal_message_id=v_portal_message.id order by id desc limit 1;
  if found and v_delivery.snapshot_id is not null then
    select * into v_snapshot from public.message_snapshots where id=v_delivery.snapshot_id;
  end if;
  select coalesce(nullif(profile.display_name,''),nullif(profile.full_name,''),profile.email::text)
  into v_sender
  from public.profiles profile
  where profile.id=v_portal_message.sender_id;
  return jsonb_build_object(
    'portal_message_id',v_portal_message.id,
    'subject',v_portal_message.subject,
    'body',v_portal_message.body,
    'created_at',v_portal_message.created_at,
    'sender_name',coalesce(v_sender,nullif(v_portal_message.sender_name_snapshot,''),'سامانه'),
    'snapshot',case when v_snapshot.id is null then null else to_jsonb(v_snapshot) end
  );
end;
$$;

-- Chat tables are read-only through the Data API.  All mutations travel
-- through the authorization-aware RPCs above; revoking a feature immediately
-- removes both the rows and every mutation path from the caller.
alter table public.chat_threads enable row level security;
alter table public.chat_members enable row level security;
alter table public.chat_messages enable row level security;
do $$
declare
  policy_row record;
begin
  for policy_row in
    select schemaname,tablename,policyname
    from pg_policies
    where schemaname='public'
      and tablename in ('chat_threads','chat_members','chat_messages')
  loop
    execute format('drop policy if exists %I on %I.%I',policy_row.policyname,policy_row.schemaname,policy_row.tablename);
  end loop;
end;
$$;
create policy chat_threads_feature_read on public.chat_threads
  for select to authenticated using(private.can_access_chat(id));
create policy chat_members_feature_read on public.chat_members
  for select to authenticated using(private.can_access_chat(thread_id));
create policy chat_messages_feature_read on public.chat_messages
