-- ---------------------------------------------------------------------------
-- Canonical chat authorization
--
-- Chat threads are operational records, not an alternate permission system.
-- The effective feature is derived from the thread itself, with system and
-- task context taking priority over the legacy `thread_type` value.  This is
-- important for legacy task-direct threads, which are stored as `direct` but
-- belong to taskChats and must follow the organizational task scope.
-- ---------------------------------------------------------------------------
create or replace function private.chat_feature_key_for_thread(
  p_thread_type text,
  p_task_id bigint,
  p_system_recipient_id uuid
)
returns text
language sql
immutable
security definer
set search_path=''
as $$
  select case
    when p_system_recipient_id is not null then 'messages'
    when p_task_id is not null then 'taskChats'
    when p_thread_type in ('public','group') then 'groupChat'
    when p_thread_type='direct' then 'directMessages'
    else null
  end;
$$;

-- Task-chat scope deliberately uses the organizational tree directly rather
-- than public.organization_can_view_task().  A task-chat grant must not
-- silently depend on a separate Kanban grant, while the same descendant rule
-- remains the reporting authority for both surfaces.
create or replace function private.organization_actor_can_access_task_chat(
  p_actor uuid,
  p_task_id bigint,
  p_action text default 'view'
)
returns boolean
language sql
stable
security definer
set search_path=''
as $$
  select coalesce(
    p_actor is not null
    and private.feature_can_access_for(p_actor,'taskChats',p_action)
    and exists(
      select 1
      from public.tasks task
      where task.id=p_task_id
        and (
          private.is_system_manager(p_actor)
          or coalesce(task.owner_id,task.created_by)=p_actor
          or coalesce(task.owner_id,task.created_by) in (
            select descendant.user_id
            from private.organization_strict_descendant_user_ids(p_actor) descendant
          )
        )
    ),
    false
  );
$$;

-- This is the one RLS predicate for all chat records.  Membership is a
-- relationship constraint for private/group chat; it is never a substitute
-- for the feature grant.  Task chat is intentionally scope-based so a direct
-- organizational superior can see the task discussion even when not manually
-- added as a chat member.  System threads are private to their recipient.
create or replace function private.can_access_chat_action(
  p_thread_id uuid,
  p_action text default 'view'
)
returns boolean
language sql
stable
security definer
set search_path=''
as $$
  with actor as (
    select auth.uid() as id
  )
  select coalesce(
    (select id from actor) is not null
    and exists(
      select 1 from public.profiles profile
      where profile.id=(select id from actor) and profile.active
    )
    and exists(
      select 1
      from public.chat_threads thread
      where thread.id=p_thread_id
        -- Deleted/inactive conversations remain readable history only.  A
        -- mutation always requires an active conversation.
        and (lower(coalesce(nullif(p_action,''),'view'))='view' or thread.is_active)
        and (
          (
            thread.system_recipient_id is not null
            and thread.system_recipient_id=(select id from actor)
            and private.feature_can_access_for(
              (select id from actor),'messages',lower(coalesce(nullif(p_action,''),'view'))
            )
          )
          or (
            thread.system_recipient_id is null
            and thread.task_id is not null
            and private.organization_actor_can_access_task_chat(
              (select id from actor),thread.task_id,lower(coalesce(nullif(p_action,''),'view'))
            )
          )
          or (
            thread.system_recipient_id is null
            and thread.task_id is null
            and thread.thread_type in ('public','group')
            and private.feature_can_access_for(
              (select id from actor),'groupChat',lower(coalesce(nullif(p_action,''),'view'))
            )
            and (
              thread.thread_type='public'
              or private.is_system_manager((select id from actor))
              or exists(
                select 1 from public.chat_members member
                where member.thread_id=thread.id and member.user_id=(select id from actor)
              )
            )
          )
          or (
            thread.system_recipient_id is null
            and thread.task_id is null
            and thread.thread_type='direct'
            and private.feature_can_access_for(
              (select id from actor),'directMessages',lower(coalesce(nullif(p_action,''),'view'))
            )
            and (
              private.is_system_manager((select id from actor))
              or exists(
                select 1 from public.chat_members member
                where member.thread_id=thread.id and member.user_id=(select id from actor)
              )
            )
          )
        )
    ),
    false
  );
$$;

