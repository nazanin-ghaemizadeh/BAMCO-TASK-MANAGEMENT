-- Final resource/storage hardening.  A resource-level site assignment is an
-- additional scope, never an alternative to the feature-level grant.  This
-- makes an explicit sitesAccess revoke immediately effective for every site.
create or replace function private.feature_can_access_resource_for(
  p_actor uuid,
  p_feature_key text,
  p_action text,
  p_resource_type text,
  p_resource_id text
)
returns boolean
language sql
stable
security definer
set search_path=''
as $$
  with active_actor as (
    select 1 from public.profiles profile where profile.id=p_actor and profile.active
  ), active_feature as (
    select 1 from public.app_features feature
    where feature.feature_key=p_feature_key and feature.active
  ), grants as (
    select grant_row.*
    from public.feature_access_grants grant_row
    where grant_row.feature_key=p_feature_key
      and grant_row.revoked_at is null
      and grant_row.resource_type=p_resource_type
      and grant_row.resource_id=p_resource_id
  ), direct_deny as (
    select 1 from grants grant_row
    where grant_row.subject_kind='user' and grant_row.user_id=p_actor
      and grant_row.effect='deny' and private.feature_grant_allows(grant_row,p_action)
  ), direct_allow as (
    select 1 from grants grant_row
    where grant_row.subject_kind='user' and grant_row.user_id=p_actor
      and grant_row.effect='allow' and private.feature_grant_allows(grant_row,p_action)
  ), role_allow as (
    select 1 from grants grant_row
    join public.organization_position_assignments assignment on assignment.user_id=p_actor
      and assignment.is_primary and assignment.valid_from<=current_date
      and (assignment.valid_to is null or assignment.valid_to>current_date)
    join public.organization_positions position on position.id=assignment.position_id and position.active
    where grant_row.subject_kind='organization_role' and grant_row.role_id=position.role_id
      and grant_row.effect='allow' and private.feature_grant_allows(grant_row,p_action)
  )
  select coalesce(
    p_actor is not null
    and exists(select 1 from active_actor)
    and exists(select 1 from active_feature)
    and private.feature_can_access_for(p_actor,p_feature_key,p_action)
    and (
      private.is_system_manager(p_actor)
      or (
        not exists(select 1 from direct_deny)
        and (exists(select 1 from direct_allow) or exists(select 1 from role_allow))
      )
    ),false);
$$;

