-- BAMCO enterprise relationship / authorization consolidation.
--
-- This migration intentionally replaces the competing access and hierarchy
-- decisions with canonical server-side contracts.  Existing access tables are
-- retained as historical migration sources; application code must call the
-- feature and organization functions defined here instead of those tables.

-- ---------------------------------------------------------------------------
-- 1. Canonical feature registry and grants
-- ---------------------------------------------------------------------------

create table if not exists public.app_features(
  feature_key text primary key,
  route_key text unique,
  title text not null,
  category text not null default 'general',
  active boolean not null default true,
  sort_order integer not null default 0,
  access_policy jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check(feature_key ~ '^[A-Za-z][A-Za-z0-9]*$')
);

create table if not exists public.feature_access_grants(
  id bigint generated by default as identity primary key,
  feature_key text not null references public.app_features(feature_key) on delete cascade,
  subject_kind text not null check(subject_kind in ('user','organization_role')),
  user_id uuid references public.profiles(id) on delete cascade,
  role_id bigint references public.organization_roles(id) on delete cascade,
  resource_type text,
  resource_id text,
  effect text not null default 'allow' check(effect in ('allow','deny')),
  can_view boolean not null default false,
  can_create boolean not null default false,
  can_edit boolean not null default false,
  can_delete boolean not null default false,
  can_export boolean not null default false,
  can_manage_access boolean not null default false,
  can_bypass_approval boolean not null default false,
  granted_by uuid references public.profiles(id) on delete set null,
  granted_at timestamptz not null default now(),
  revoked_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  check(
    (subject_kind='user' and user_id is not null and role_id is null)
    or
    (subject_kind='organization_role' and role_id is not null and user_id is null)
  )
);

create unique index if not exists feature_access_grants_active_subject_feature_idx
  on public.feature_access_grants(
    feature_key,
    subject_kind,
    coalesce(user_id,'00000000-0000-0000-0000-000000000000'::uuid),
    coalesce(role_id,0),
    coalesce(resource_type,''),
    coalesce(resource_id,'')
  ) where revoked_at is null;
create index if not exists feature_access_grants_user_active_idx
  on public.feature_access_grants(user_id,feature_key) where revoked_at is null;
create index if not exists feature_access_grants_role_active_idx
  on public.feature_access_grants(role_id,feature_key) where revoked_at is null;

