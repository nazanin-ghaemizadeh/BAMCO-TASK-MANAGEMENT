-- An unassigned intake task is valid for a system manager.  Its task-chat
-- thread therefore has no second occupant to insert; keep the actor/selected
-- recipient relation valid instead of attempting a NULL chat_members row.
create or replace function private._bamco_impl_chat_ensure_task(p_task_id bigint)
returns uuid
language plpgsql
security definer
set search_path=''
as $$
declare
  v_actor uuid:=auth.uid();
  v_thread_id uuid;
  v_owner uuid;
  v_title text;
begin
  if v_actor is null or not private.organization_actor_can_access_task_chat(v_actor,p_task_id,'view') then
    raise exception 'forbidden' using errcode='42501';
  end if;
  select coalesce(task.owner_id,task.created_by),task.title
  into v_owner,v_title
  from public.tasks task
  where task.id=p_task_id;
  if not found then
    raise exception 'task_not_found' using errcode='P0002';
  end if;
  select thread.id into v_thread_id
  from public.chat_threads thread
  where thread.thread_type='task' and thread.task_id=p_task_id and thread.is_active
  limit 1;
  if v_thread_id is null then
    if not private.organization_actor_can_access_task_chat(v_actor,p_task_id,'create') then
      raise exception 'forbidden' using errcode='42501';
    end if;
    begin
      insert into public.chat_threads(thread_type,title,task_id,created_by)
      values('task','تسک: '||left(coalesce(v_title,''),100),p_task_id,v_actor)
      returning id into v_thread_id;
    exception when unique_violation then
      select thread.id into v_thread_id
      from public.chat_threads thread
      where thread.thread_type='task' and thread.task_id=p_task_id and thread.is_active
      limit 1;
    end;
  end if;
  insert into public.chat_members(thread_id,user_id)
  values(v_thread_id,v_actor)
  on conflict do nothing;
  if v_owner is not null
     and v_owner is distinct from v_actor
     and exists(select 1 from public.profiles profile where profile.id=v_owner and profile.active) then
    insert into public.chat_members(thread_id,user_id)
    values(v_thread_id,v_owner)
    on conflict do nothing;
  end if;
  return v_thread_id;
end;
$$;

create or replace function private._bamco_impl_chat_ensure_task_direct(
  p_task_id bigint,
  p_other_user uuid
)
returns uuid
language plpgsql
security definer
set search_path=''
as $$
declare
  v_actor uuid:=auth.uid();
  v_owner uuid;
  v_title text;
  v_display_id bigint;
  v_key text;
  v_thread_id uuid;
begin
  if v_actor is null or p_other_user is null or p_other_user=v_actor
     or not private.organization_actor_can_access_task_chat(v_actor,p_task_id,'view')
     or not private.organization_actor_can_access_task_chat(p_other_user,p_task_id,'view')
     or not exists(
       select 1 from public.profiles profile
       where profile.id=p_other_user and profile.active and profile.messaging_enabled
     ) then
    raise exception 'invalid_recipient' using errcode='42501';
  end if;
  select coalesce(task.owner_id,task.created_by),task.title,task.legacy_id
  into v_owner,v_title,v_display_id
  from public.tasks task
  where task.id=p_task_id;
  if not found then
    raise exception 'task_not_found' using errcode='P0002';
  end if;
  v_key:='task:'||p_task_id::text||':'||case
    when v_actor::text<p_other_user::text then v_actor::text||':'||p_other_user::text
    else p_other_user::text||':'||v_actor::text
  end;
  select thread.id into v_thread_id
  from public.chat_threads thread
  where thread.direct_key=v_key
  limit 1;
  if v_thread_id is null then
    if not private.organization_actor_can_access_task_chat(v_actor,p_task_id,'create') then
      raise exception 'forbidden' using errcode='42501';
    end if;
    begin
      insert into public.chat_threads(thread_type,title,task_id,direct_key,created_by)
      values(
        'direct',
        'وظیفه '||coalesce(v_display_id,p_task_id)::text||' — '||left(coalesce(v_title,''),90),
        p_task_id,v_key,v_actor
      )
      returning id into v_thread_id;
    exception when unique_violation then
      select thread.id into v_thread_id
      from public.chat_threads thread
      where thread.direct_key=v_key
      limit 1;
    end;
  end if;
  insert into public.chat_members(thread_id,user_id)
  values(v_thread_id,v_actor),(v_thread_id,p_other_user)
  on conflict do nothing;
  if v_owner is not null
     and v_owner is distinct from v_actor
     and v_owner is distinct from p_other_user
     and exists(select 1 from public.profiles profile where profile.id=v_owner and profile.active) then
    insert into public.chat_members(thread_id,user_id)
    values(v_thread_id,v_owner)
    on conflict do nothing;
  end if;
  return v_thread_id;
end;
$$;

