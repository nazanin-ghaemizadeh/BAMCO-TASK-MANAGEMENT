  end if;
  if v_user is not null and v_user is distinct from auth.uid() then
    perform private.emit_relationship_event(
      v_user,v_action,v_title,v_body,'organization_position',v_position::text,
      jsonb_build_object('position_id',v_position,'actor_id',auth.uid())
    );
  end if;
