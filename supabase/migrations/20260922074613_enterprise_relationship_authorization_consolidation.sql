-- Existing data uses corporate-looking login values.  They have been checked
-- for unique, valid local parts before this migration; normalize Auth and the
-- protected login mirror without touching profiles.email or user IDs.
do $$
declare
  v_bad integer;
  v_duplicate integer;
begin
  with normalized as (
    select profile.id,lower(split_part(coalesce(nullif(btrim(profile.login_name),''),account.email),'@',1)) as login_name
    from public.profiles profile join auth.users account on account.id=profile.id
  )
  select count(*) filter(where login_name !~ '^[a-z0-9][a-z0-9._-]{2,63}$'),
         count(*)-count(distinct login_name)
    into v_bad,v_duplicate
  from normalized;
  if v_bad>0 or v_duplicate>0 then
    raise exception 'نام‌های کاربری موجود برای جداسازی امن از ایمیل سازمانی معتبر یا یکتا نیستند.' using errcode='23505';
  end if;
  update auth.users account
     set email=normalized.login_name||'@no-email.invalid',
         email_confirmed_at=coalesce(account.email_confirmed_at,now())
    from (
      select profile.id,lower(split_part(coalesce(nullif(btrim(profile.login_name),''),source.email),'@',1)) as login_name
      from public.profiles profile join auth.users source on source.id=profile.id
    ) normalized
   where account.id=normalized.id
     and account.email is distinct from normalized.login_name||'@no-email.invalid';
  update public.profiles profile
     set login_name=normalized.login_name
    from (
      select profile_row.id,lower(split_part(coalesce(nullif(btrim(profile_row.login_name),''),account.email),'@',1)) as login_name
      from public.profiles profile_row join auth.users account on account.id=profile_row.id
    ) normalized
   where profile.id=normalized.id and profile.login_name is distinct from normalized.login_name;
end;
$$;

