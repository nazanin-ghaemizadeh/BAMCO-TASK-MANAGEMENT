-- ---------------------------------------------------------------------------
-- Relationship event fan-out and final RPC exposure boundary
-- ---------------------------------------------------------------------------
-- These triggers deliberately carry identifiers and action metadata instead
-- of encoding navigation in prose.  They complement the approval events
-- above and give every affected client a narrow, RLS-filtered invalidation.
create or replace function private.emit_task_relationship_change()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_recipient uuid;
  v_action text;
  v_title text;
  v_body text;
  v_task_id bigint;
begin
  if tg_op='DELETE' then
    v_recipient:=coalesce(old.owner_id,old.created_by);
    v_task_id:=old.id;
    v_action:='task_deleted';
    v_title:='وظیفه حذف شد';
    v_body:=coalesce(nullif(old.title,''),'یک وظیفه')||' حذف شد.';
  elsif tg_op='INSERT' then
    v_recipient:=coalesce(new.owner_id,new.created_by);
    v_task_id:=new.id;
    v_action:='task_assigned';
    v_title:='وظیفه جدید به شما واگذار شد';
    v_body:=coalesce(nullif(new.title,''),'یک وظیفه جدید')||' برای شما ثبت شد.';
  elsif old.owner_id is distinct from new.owner_id then
    v_recipient:=coalesce(new.owner_id,new.created_by);
    v_task_id:=new.id;
    v_action:='task_reassigned';
    v_title:='متولی وظیفه تغییر کرد';
    v_body:=coalesce(nullif(new.title,''),'یک وظیفه')||' به شما واگذار شد.';
  elsif (old.title,old.description,old.status,old.priority,old.start_date,old.due_date,old.archived)
        is distinct from
        (new.title,new.description,new.status,new.priority,new.start_date,new.due_date,new.archived) then
    v_recipient:=coalesce(new.owner_id,new.created_by);
    v_task_id:=new.id;
    v_action:='task_changed';
    v_title:='وظیفه به‌روزرسانی شد';
    v_body:=coalesce(nullif(new.title,''),'یک وظیفه')||' تغییر کرده است.';
  else
    return new;
  end if;

  if v_recipient is not null and v_recipient is distinct from auth.uid() then
    perform private.emit_relationship_event(
      v_recipient,v_action,v_title,v_body,'task',v_task_id::text,
      jsonb_build_object('task_id',v_task_id,'actor_id',auth.uid())
    );
  end if;
  if tg_op='UPDATE' and auth.uid() is not null and auth.uid() is distinct from coalesce(new.owner_id,new.created_by) then
    insert into public.audit_trail(actor_id,action,target_type,target_id,old_data,new_data,metadata)
    values(
      auth.uid(),'supervisor_task_changed','task',new.id::text,to_jsonb(old),to_jsonb(new),
      jsonb_build_object('canonical','tasks','owner_id',new.owner_id)
    );
  end if;
  if tg_op='DELETE' then return old; end if;
  return new;
end;
$$;
drop trigger if exists tasks_relationship_event on public.tasks;
create trigger tasks_relationship_event
after insert or update or delete on public.tasks
for each row execute function private.emit_task_relationship_change();

