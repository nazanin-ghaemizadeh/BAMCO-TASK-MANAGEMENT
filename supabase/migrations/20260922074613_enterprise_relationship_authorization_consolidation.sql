create or replace function private._bamco_impl_chat_manage_group(
  p_thread_id uuid,
  p_title text,
  p_member_ids uuid[] default '{}'::uuid[],
  p_delete boolean default false
)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare
  v_actor uuid:=auth.uid();
  v_member uuid;
  v_action text:=case when coalesce(p_delete,false) then 'delete' else 'edit' end;
begin
  if v_actor is null
     or not private.can_access_chat_action(p_thread_id,v_action)
     or not exists(
       select 1 from public.chat_threads thread
       where thread.id=p_thread_id and thread.thread_type='group' and thread.is_active
