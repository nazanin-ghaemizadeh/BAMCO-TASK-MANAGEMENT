create or replace function private._bamco_impl_chat_send_message(
  p_thread_id uuid,
  p_body text,
  p_reply_to bigint default null
)
returns bigint
language plpgsql
security definer
set search_path=''
as $$
declare
  v_actor uuid:=auth.uid();
  v_message_id bigint;
begin
  if v_actor is null
     or not private.can_access_chat_action(p_thread_id,'create')
     or not exists(select 1 from public.chat_threads thread where thread.id=p_thread_id and thread.is_active) then
    raise exception 'forbidden' using errcode='42501';
  end if;
  if length(btrim(coalesce(p_body,'')))<1 or length(p_body)>10000 then
    raise exception 'invalid_message' using errcode='22023';
  end if;
  if p_reply_to is not null and not exists(
    select 1 from public.chat_messages message
    where message.id=p_reply_to and message.thread_id=p_thread_id and message.deleted_at is null
  ) then
    raise exception 'invalid_reply' using errcode='22023';
  end if;
  insert into public.chat_messages(thread_id,sender_id,body,reply_to)
  values(p_thread_id,v_actor,btrim(p_body),p_reply_to)
  returning id into v_message_id;
  update public.chat_threads set updated_at=now() where id=p_thread_id;
  insert into public.chat_members(thread_id,user_id,last_read_at)
  values(p_thread_id,v_actor,now())
  on conflict(thread_id,user_id) do update set last_read_at=excluded.last_read_at;
  return v_message_id;
end;
$$;

create or replace function private._bamco_impl_chat_edit_message(
  p_message_id bigint,
  p_body text
)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare
  v_message public.chat_messages%rowtype;
begin
  select * into v_message
  from public.chat_messages message
  where message.id=p_message_id and message.deleted_at is null
  for update;
