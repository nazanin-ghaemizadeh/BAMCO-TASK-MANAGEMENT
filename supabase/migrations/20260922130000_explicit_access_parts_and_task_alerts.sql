-- ---------------------------------------------------------------------------
-- 2. Part handover register. The columns intentionally match the operational
-- table shown in the parts workspace and the feature permission contract.
-- ---------------------------------------------------------------------------
create table public.part_handovers(
  id bigint generated by default as identity primary key,
  part_name text not null check(length(btrim(part_name))>0),
  technical_number text not null check(length(btrim(technical_number))>0),
  received_from text,
  received_by text,
  returned_from text,
  returned_by text,
  delivery_type text not null check(delivery_type in ('permanent','temporary')),
  return_due_date date,
  reason text,
  registered_at timestamptz not null default now(),
  notes text,
  created_by uuid not null default auth.uid() references public.profiles(id),
  updated_at timestamptz not null default now(),
  check(
    (delivery_type='temporary' and return_due_date is not null)
    or (delivery_type='permanent' and return_due_date is null)
  )
);

create index part_handovers_registered_at_idx
  on public.part_handovers(registered_at desc,id desc);

