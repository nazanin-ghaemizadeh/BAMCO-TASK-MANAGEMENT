const test=require('node:test');
const assert=require('node:assert/strict');
const {fixture,until}=require('./helpers/app-fixture.cjs');
test('mileage costs opens independently and saves a freely entered cost type',async t=>{
 const f=await fixture({tables:{mileage_cost_entries:[],mileage_cost_attachments:[],petty_cash_entries:[{id:'cash-only',entry_no:1,event_date:'2026-11-11',entry_type:'expense',amount:'123',category:'بنزین',status:'active'}]}});
 t.after(()=>f.dispose());
 await f.open('mileageCosts');
 await until(()=>f.d.querySelector('#addMileageEntry'));
 f.d.querySelector('#addMileageEntry').click();
 const form=f.d.querySelector('#mileageCostsDialog form');assert(form);
 assert.equal(form.elements.category.tagName,'INPUT');
 assert.deepEqual([...form.querySelectorAll('datalist option')].map(x=>x.value),['نهار','شام','صبحانه','بنزین','اقامت']);
 assert(!f.d.querySelector('#mileageCostsView thead').textContent.includes('مانده'));
 assert.equal(f.d.querySelector('#mileageCostsBody td[colspan]').colSpan,10);
 form.elements.category.value='هزینه اختصاصی پیمایش';form.elements.amount.value='123456';form.elements.responsible_id.value='test-manager';
 await form.onsubmit({preventDefault(){}});
 await until(()=>f.d.querySelector('#mileageCostsBody').textContent.includes('هزینه اختصاصی پیمایش'));
 assert(!f.d.querySelector('#mileageCostsBody').textContent.includes('بنزین'));
 assert.equal(f.d.querySelector('#mileageCostsBody tr').children.length,10);
 f.d.querySelector('#addMileageEntry').click();
 assert([...f.d.querySelectorAll('#mileageCostCategories option')].some(x=>x.value==='هزینه اختصاصی پیمایش'));
 f.d.querySelector('#mileageCostsDialog').close();
 f.d.querySelector('#mileageDashboardToggle').click();
 await until(()=>f.d.querySelector('#mileageDashboardDialog')?.open);
 assert(f.d.querySelector('#mileageDashboardDialog').classList.contains('cash-dashboard-dialog'));
 assert.equal(f.d.querySelectorAll('#mileageDashboardDialog .cash-summary article').length,4);
 assert(f.d.querySelector('#mileageCostsSummary').classList.contains('hidden'));
 f.d.querySelector('#mileageDashboardDialog [data-close]').click();
 let exported;
 f.w.ensureBamcoXLSX=async()=>({utils:{aoa_to_sheet:rows=>({rows:JSON.parse(JSON.stringify(rows))}),book_new:()=>({SheetNames:[],Sheets:{}}),book_append_sheet:(wb,sheet,name)=>{wb.SheetNames.push(name);wb.Sheets[name]=sheet;}},writeFile:(wb,name)=>{exported={wb,name};}});
 f.d.querySelector('#exportMileage').click();await until(()=>exported);
 assert.deepEqual(exported.wb.SheetNames,['ریز هزینه‌های پیمایش','جمع‌بندی نوع هزینه']);
 const sheet=exported.wb.Sheets['ریز هزینه‌های پیمایش'];
 assert.equal(sheet['!views'][0].rightToLeft,true);assert.equal(sheet['!freeze'].ySplit,1);
 assert.equal(sheet.rows[1][3],123456);
 assert(exported.wb.Sheets['جمع‌بندی نوع هزینه'].rows.some(row=>row[1]==='هزینه اختصاصی پیمایش'&&row[3]===123456));
 await f.open('pettyCash');await until(()=>f.d.querySelector('#pettyCashBody').textContent.includes('بنزین'));
 assert(!f.d.querySelector('#pettyCashBody').textContent.includes('هزینه اختصاصی پیمایش'));
});
