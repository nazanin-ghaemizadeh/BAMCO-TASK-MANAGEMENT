const digest = value => createHash('sha256').update(value).digest('hex').slice(0, 16);
const read = path => readFile(new URL(path, root), 'utf8');

async function buildJavascript() {
  const sources = await Promise.all(javascript.map(read));
  const body = sources.map((source, index) =>
    `/* source: ${javascript[index]} */\n${source.trim()}\n;`
  ).join('\n\n');
  return `/* Generated by scripts/build-static-bundles.mjs. Do not edit. */\n/* sha256: ${digest(body)} */\n${body}\n`;
}

async function buildCss() {
  const mobile = await read('assets/css/responsive.css');
  const sources = await Promise.all(stylesheets.map(async path => {
    let source = await read(path);
    if (path.endsWith('/department-entry.css')) {
      source = source.replace(/@import\s+url\([^)]*responsive\.css[^)]*\);?\s*/, `/* source: assets/css/responsive.css */\n${mobile.trim()}\n`);
    }
    return `/* source: ${path} */\n${source.trim()}`;
  }));
  const body = sources.join('\n\n');
  return `/* Generated by scripts/build-static-bundles.mjs. Do not edit. */\n/* sha256: ${digest(body)} */\n${body}\n`;
}

async function sync(path, expected) {
  const url = new URL(path, root);
  if (checkOnly) {
    const current = await readFile(url, 'utf8').catch(() => '');
    if (current !== expected) throw new Error(`${path} is stale; run npm run build:assets`);
    return;
  }
  await writeFile(url, expected);
}

async function syncEntryCritical() {
  const source = await read('assets/css/department-entry.css');
  const critical = 'html,body{margin:0;min-height:100%;background:#f4f8f5}\n' + source
    .split('/* Other small forms')[0]
    .replace(/@import[^;]+;\s*/, '')
    .replaceAll("../fonts/", "assets/fonts/").trim();
  const index = await read('index.html');
  const expected = index.replace(/<style id="entryCritical">[\s\S]*?<\/style>/, `<style id="entryCritical">${critical}</style>`);
  if (!index.includes('<style id="entryCritical">')) throw Error('Entry critical style missing');
  if (checkOnly && index !== expected) throw Error('Entry critical CSS is stale; run npm run build:assets');
  if (!checkOnly && index !== expected) await writeFile(new URL('index.html', root), expected);
}
await syncEntryCritical();

